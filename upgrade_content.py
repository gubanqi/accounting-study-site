        for r in c['sourceAudit']:
            titles='、'.join(u['title'] for u in c['lessons'] if u['id'] in r['lessonIds'])
            lines.append(f"|{r['source']+1}|{r['page']}|{r['heading'].replace('|','/')}|{titles or '—'}|{'、'.join(r['exampleIds']) or '—'}|{'、'.join(r['practiceIds']) or '—'}|{r['status']}|")
