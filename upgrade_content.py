def p(text):
    return ''.join('<p>'+html.escape(x).replace('\n','<br>')+'</p>' for x in text.split('\n\n'))

def L(ch,key,title,requirement,refs,explanation,rules,pitfalls,example,solution,practice):
    """refs为(本章第几份PDF,起页,止页)，PDF页码从1开始。"""
    LESSONS[str(ch)].append(dict(id=key,title=title,requirement=requirement,
        sourceRefs=[dict(source=s-1,start=a,end=b) for s,a,b in refs],
        origin='课件讲解' if refs else '已提供题册补充',explanation=explanation,
        rules=rules.split('|'),pitfalls=pitfalls.split('|'),
        examples=[dict(id=f'EX{ch}-{key}',stem=example,solution=p(solution),origin='依据已提供材料自编教学例题')],
        practiceIds=practice.split('|')))

def Q(ch,n,kind,stem,options,correct,explanation,topic,level='标准',source=''):
    if kind=='判断':options=['正确','错误'];correct=[0 if correct else 1]
    elif isinstance(correct,int):correct=[correct]
    ADDITIONS[str(ch)].append(dict(id=f'UP{ch}-{n:02}',type=kind,stem=stem,options=options,
        correct=correct,explanation=p(explanation),topic=topic,level=level,
        origin='依据课件自编',source=source or f'第{ch}章已提供课件；配套自编练习'))

